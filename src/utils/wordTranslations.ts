/**
 * Given an English word clicked by the student, finds the matching Arabic word or phrase
 * inside the Arabic translation line with smart morphological and contextual alignment.
 */
export function findMatchingArabicInLine(
  englishWord: string,
  arabicLine: string,
  lineId?: string,
  englishLine?: string,
  wordIndexInLine?: number
): string | null {
  if (!englishWord || !arabicLine) return null;

  const clean = englishWord.toLowerCase().replace(/[^a-z0-9'-]/g, '');
  if (!clean) return null;

  // 1. Line Custom Alignment check
  if (lineId && LINE_CUSTOM_ALIGNMENTS[lineId]?.[clean]) {
    const match = LINE_CUSTOM_ALIGNMENTS[lineId][clean];
    if (arabicLine.includes(match)) return match;
  }

  // Morphological validation helper
  const checkCandidate = (c: string): string | null => {
    if (arabicLine.includes(c)) return c;

    // Definite article 'الـ' morphs (للـ، والـ، بالـ، كالـ، فالـ)
    if (c.startsWith('ال')) {
      const stem = c.slice(2);
      const variations = ['لل' + stem, 'وال' + stem, 'بال' + stem, 'كال' + stem, 'فال' + stem];
      for (const v of variations) {
        if (arabicLine.includes(v)) return v;
      }
    } else {
      const variations = ['ال' + c, 'وال' + c, 'بال' + c, 'لل' + c, 'كال' + c, 'فال' + c];
      for (const v of variations) {
        if (arabicLine.includes(v)) return v;
      }
    }

    // Standard Arabic single-letter prefixes
    for (const p of ['و', 'ف', 'ب', 'ل', 'ك', 'وال', 'لل']) {
      if (arabicLine.includes(p + c)) return p + c;
    }

    // Accusative Tanween check (e.g., رائع -> رائعاً)
    if (arabicLine.includes(c + 'اً')) return c + 'اً';
    if (arabicLine.includes(c + 'ا')) return c + 'ا';

    return null;
  };

  // 2. Determiners 'the', 'a', 'an' context lookahead
  if (['the', 'a', 'an'].includes(clean) && englishLine && wordIndexInLine !== undefined) {
    const tokens = englishLine.split(/\s+/);
    for (let offset = 1; offset <= 2; offset++) {
      if (wordIndexInLine + offset < tokens.length) {
        const nextWord = tokens[wordIndexInLine + offset].toLowerCase().replace(/[^a-z0-9'-]/g, '');
        const nextCandidates = VOCABULARY_MAP[nextWord];
        if (nextCandidates) {
          for (const nc of nextCandidates) {
            const m = checkCandidate(nc);
            if (m) return m;
          }
        }
      }
    }
  }

  // 3. Direct dictionary match
  const candidates = VOCABULARY_MAP[clean];
  if (candidates) {
    for (const c of candidates) {
      const m = checkCandidate(c);
      if (m) return m;
    }
  }

  // 4. Stemming / Contractions handling
  const stem = clean
    .replace(/n't$/, '')
    .replace(/'s$/, '')
    .replace(/s$/, '')
    .replace(/ed$/, '')
    .replace(/ing$/, '');

  if (stem.length >= 3 && VOCABULARY_MAP[stem]) {
    for (const c of VOCABULARY_MAP[stem]) {
      const m = checkCandidate(c);
      if (m) return m;
    }
  }

  return null;
}
